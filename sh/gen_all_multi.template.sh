#!/bin/sh
# Generated from gen_all_multi.template.sh by setup.sh

# --- Usage ---
# ./gen_all_multi.sh [--launch]
#
# Options:
#   --launch    Automatically execute the generated launch script.

# =============================================================================
# Edit: Simulation name (gets put in paramsmulti and handed to gen_all_multi)
# =============================================================================
SIMU_NAME="jupiter"
# =============================================================================

MULTI_DIR="__MULTI_DIR__"
BIN_DIR="__BIN_DIR__"
TMP_DIR="__TMP_DIR__"

# =============================================================================
# Edit: Simulation parameters (written to paramsmulti.in)
# =============================================================================
T0="0.0d0"
TSTOP="1.0e2"
DT="0.05"
DTOUT="1.0e1"
DTDUMP="1.0e1"
LFLAGS="F T F F T F"
RMIN="0.005"
RMAX="1000."
RMAXU="-1."
QMIN="-1."
LCLOSE="F"
FOPENSTAT="new"
# =============================================================================

# =============================================================================
# Directory containing this script (and the launch template).
# =============================================================================
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
LAUNCH_TEMPLATE="${SCRIPT_DIR}/launch_all_simulations.template.sh"

# =============================================================================
# Create simulation directory.
# =============================================================================
SIMU_DIR="${MULTI_DIR}/simu_${SIMU_NAME}"
mkdir -p "$SIMU_DIR"

# =============================================================================
# Parse arguments
# =============================================================================
DO_LAUNCH=0
for arg in "$@"; do
    case "$arg" in
        --launch)
            DO_LAUNCH=1
            ;;
        *)
            echo "ERROR: Unknown option: $arg" >&2
            echo "Usage: $0 [--launch]" >&2
            exit 1
            ;;
    esac
done

# =============================================================================
# Validate launch template
# =============================================================================
if [ ! -f "$LAUNCH_TEMPLATE" ]; then
    echo "[ERROR] Launch template not found: $LAUNCH_TEMPLATE" >&2
    exit 1
fi

# =============================================================================
# Generate paramsmulti.in directly in simulation directory.
# =============================================================================
cat > "${SIMU_DIR}/paramsmulti.in" <<PARAMS
${T0} ${TSTOP} ${DT}
${DTOUT} ${DTDUMP}
${LFLAGS}
${RMIN}  ${RMAX} ${RMAXU} ${QMIN} ${LCLOSE}
${TMP_DIR}
run_${SIMU_NAME}
bin_${SIMU_NAME}
${FOPENSTAT}
PARAMS

# =============================================================================
# Move into simulation directory to run from there.
# =============================================================================
cd "$SIMU_DIR" || exit 1

# =============================================================================
# Edit Simulation parameters (directly piped to gen_all_multi)
# =============================================================================
${BIN_DIR}/gen_all_multi <<!
1   !   AU & Years
0   !   Invariable plane
0   !   No planet radii
1.   ! Mass of star
1   ! Number of planets
1.  ! Mass In Jupiter masses
5.2 0.03 0.000 0.00 0.00 0. ! a e i Omega omega M
plmulti.in
2.0
654876543
simu_${SIMU_NAME}
tpmulti.in
paramsmulti.in
100 ! # of particles
50    ! # of particles in first file
0. 0.01 ! Ex
3.  ! Max inc
2.4 2.6 !Amin & Amax
0
!

# =============================================================================
# Generate launch script from template
# =============================================================================
LAUNCH_SCRIPT="${SIMU_DIR}/launch_all_simulations.sh"

sed \
    -e "2s|.*|# launch_all_simulations.sh for simu_${SIMU_NAME}|" \
    -e "3s|.*|# Generated by gen_all_multi.sh on $(date)|" \
    "$LAUNCH_TEMPLATE" > "$LAUNCH_SCRIPT"

chmod +x "$LAUNCH_SCRIPT"
echo ""
echo "[INFO] Created: $LAUNCH_SCRIPT"

# =============================================================================
# Optionally launch
# =============================================================================
if [ "$DO_LAUNCH" -eq 1 ]; then
    echo "[INFO] Launching all simulations..."
    "$LAUNCH_SCRIPT"
fi
